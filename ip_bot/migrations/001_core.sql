CREATE TABLE IF NOT EXISTS profiles (user_id BIGINT PRIMARY KEY, state JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS events (
    seq BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE, user_id BIGINT NOT NULL,
    text TEXT NOT NULL, reply TEXT, delivered BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS events_pending_idx ON events(seq) WHERE NOT delivered;
CREATE INDEX IF NOT EXISTS events_user_seq_idx ON events(user_id, seq);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value JSONB NOT NULL);
