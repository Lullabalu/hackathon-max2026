def make_pdf(title, text):
    name = 'NotoSansBot'
    if name not in pdfmetrics.getRegisteredFontNames():
        font = Path(__file__).resolve().parent.parent / 'config/fonts/NotoSans-Regular.ttf'
        pdfmetrics.registerFont(TTFont(name, str(font)))
    output = io.BytesIO()
    canvas = Canvas(output, pagesize=A4, pageCompression=1)
    canvas.setTitle(title)
    width, height = A4
    y = height - 45
    def page():
        nonlocal y
        canvas.showPage()
        y = height - 45
    canvas.setFont(name, 15)
    for line in simpleSplit(title, name, 15, width - 80):
        canvas.drawString(40, y, line)
        y -= 23
    y -= 10
    for paragraph in text.splitlines():
        for line in simpleSplit(paragraph, name, 10, width - 80) or ['']:
            if y < 45:
                page()
            canvas.setFont(name, 10)
            canvas.drawString(40, y, line)
            y -= 15
    canvas.save()
    return output.getvalue()


def form_draft(state):
    form = (state or {}).get('form', {})
    names = {'surname': 'Фамилия', 'name': 'Имя', 'patronymic': 'Отчество',
             'inn': 'ИНН (при наличии)', 'email': 'Email для результата регистрации'}
    lines = ['ЧЕРНОВИК ДАННЫХ ДЛЯ Р21001 — НЕ ЗАЯВЛЕНИЕ ДЛЯ ПОДАЧИ',
             f'Составлен: {date.today().isoformat()}']
    lines += [f'{label}: {form.get(key, "не заполнено")}' for key, label in names.items()]
    lines += [f"Регион: {(state or {}).get('answers', {}).get('region', 'не указан')}"]
    codes = (state or {}).get('okved', {})
    if codes.get('primary'):
        lines.append('Основной ОКВЭД: ' + codes['primary']['code'])
        lines.append('Дополнительные: ' + ', '.join(item['code'] for item in codes.get('additional', [])))
    lines += ['\nПаспорт, адрес по ФИАС и остальные обязательные сведения заполните в официальном сервисе ФНС. '
              'Этот файл помогает перенести выбранные данные, но не заменяет установленную форму и не подаётся в ФНС.',
              REGISTRATION, 'Официальный бланк: ' + FORM_URL]
    return '\n'.join(lines)
