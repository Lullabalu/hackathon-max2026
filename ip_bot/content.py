def checklist(answers: dict) -> str:
    employee_step = (
        "При сравнении режимов учесть планируемый найм и расходы на работников."
        if answers["employees"] > 0
        else "При сравнении режимов указать, что работников по трудовым договорам нет."
    )
    return (
        "Следующие шаги по вашей анкете:\n"
        f"1. Уточнить основной вид деятельности: {answers['activity']}. "
        "Подобрать и проверить ОКВЭД.\n"
        f"2. Сравнить режимы для региона «{answers['region']}» с учётом "
        "доходов, расходов и покупателей.\n"
        f"3. {employee_step}\n"
        "4. На странице ФНС выбрать способ подачи заявления на регистрацию ИП.\n"
        "5. Проверить документы и сроки для выбранного способа и режима.\n\n"
        "/okved — подобрать коды; /taxes — сравнить режимы; /register — персональные документы. "
        "Официальные сервисы для проверки:\n"
        f"{TAX_URL}\n{REGISTRATION_URL}\n\n"
        "Документы никуда не отправлены. /profile — ваши ответы, /back — исправить."
    )
